export function isLearnTopicId(value: string): value is LearnTopicId {
  return LEARN_TOPIC_IDS.some((id) => id === value);
}

export function getLearnTopic(topicId: string): LearnTopic | null {
  if (!isLearnTopicId(topicId)) {
    return null;
  }
  return LEARN_TOPICS.find((topic) => topic.id === topicId) ?? null;
}

export function getLearnTopicsBySection(section: LearnSection): LearnTopic[] {
  return LEARN_TOPICS.filter((topic) => topic.section === section);
}

export async function getPracticeHrefForCategory(
  categoryName: string
): Promise<string> {
  const supabase = await createClient();
  const { data } = await supabase
    .from("categories")
    .select("id")
    .eq("name", categoryName)
    .maybeSingle();

  if (!data?.id) {
    return "/practice";
  }

  return `/practice?category_id=${data.id}`;
}
