export function isLearnTopicId(value: string): value is LearnTopicId {
  return LEARN_TOPICS.some((topic) => topic.id === value);
}

export function getLearnTopic(topicId: string): LearnTopic | null {
  if (!isLearnTopicId(topicId)) {
    return null;
  }
  return LEARN_TOPICS.find((topic) => topic.id === topicId) ?? null;
}

export function getLearnTopicsBySection(section: LearnSection): LearnTopic[] {
  return LEARN_TOPICS.filter((topic) => topic.section === section);
}

export function getDiagramFigureNumber(topicId: DiagramLearnTopicId): number {
  if (currentExam.id === "boiler2") {
    const index = (BOILER2_DIAGRAM_TOPIC_IDS as readonly string[]).indexOf(topicId);
    return index >= 0 ? index + 1 : 1;
  }
  if (currentExam.id === "crane_all") {
    const index = (CRANE_ALL_DIAGRAM_TOPIC_IDS as readonly string[]).indexOf(topicId);
    return index >= 0 ? index + 1 : 1;
  }
  if (currentExam.id === "mobile_crane") {
    const index = (MOBILE_CRANE_DIAGRAM_TOPIC_IDS as readonly string[]).indexOf(topicId);
    return index >= 0 ? index + 1 : 1;
  }
  if (currentExam.id === "xray") {
    const index = (XRAY_DIAGRAM_TOPIC_IDS as readonly string[]).indexOf(topicId);
    return index >= 0 ? index + 1 : 1;
  }
  if (currentExam.id === "diver") {
    const index = (DIVER_DIAGRAM_TOPIC_IDS as readonly string[]).indexOf(topicId);
    return index >= 0 ? index + 1 : 1;
  }
  const index = (DIAGRAM_TOPIC_IDS as readonly string[]).indexOf(topicId);
  return index >= 0 ? index + 1 : 1;
}

export function getTablePlateNumber(
  topicId: TableLearnTopicId,
  tableIndex: number
): number {
  let offset = 0;
  for (const topic of LEARN_TOPICS) {
    if (topic.contentType !== "table") {
      continue;
    }
    if (topic.id === topicId) {
      return offset + tableIndex + 1;
    }
    offset += topic.tables.length;
  }
  return tableIndex + 1;
}

export function getSectionTopicNumber(topic: LearnTopic): number {
  return (
    getLearnTopicsBySection(topic.section).findIndex((item) => item.id === topic.id) +
    1
  );
}

export async function getPracticeHrefForCategory(
  categoryName: string
): Promise<string> {
  const supabase = await createClient();
  const { data } = await supabase
    .from("categories")
    .select("id")
    .eq("exam_id", currentExam.id)
    .eq("name", categoryName)
    .maybeSingle();

  if (!data?.id) {
    return "/practice";
  }

  return `/practice?category_id=${data.id}`;
}
